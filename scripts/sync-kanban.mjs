import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const inputIndex = process.argv.indexOf('--input');
if (inputIndex !== -1 && !process.argv[inputIndex + 1]) throw new Error('--input requires a file');
const gh = process.env.THENFRAME_GH_PATH || 'gh';
const raw = inputIndex !== -1 ? readFileSync(process.argv[inputIndex + 1], 'utf8')
  : execFileSync(gh, ['project', 'item-list', '1', '--owner', 'phangsx25',
    '--format', 'json', '--limit', '1000'], { encoding: 'utf8' });
const board = JSON.parse(raw.replace(/^\uFEFF/, ''));
if (!Array.isArray(board.items) || !Number.isInteger(board.totalCount)
  || board.items.length !== board.totalCount) throw new Error('Incomplete Kanban response');
const estimates = [3, 3, 5, 5, 8, 5, 5, 5, 8, 8, 5, 3, 3];
const knownStatuses = new Set(['Backlog', 'Sprint Backlog', 'In progress', 'In review', 'Done']);
const stories = estimates.map((points, index) => {
  const id = `US${String(index + 1).padStart(2, '0')}`;
  const matches = board.items.filter(item => new RegExp(`^${id}\\b`).test(item.title));
  if (matches.length !== 1) throw new Error(`Expected one ${id} card`);
  const item = matches[0];
  if (!knownStatuses.has(item.status) || !/^https:\/\/github\.com\/[\w.-]+\/[\w.-]+\/issues\/\d+$/.test(item.content?.url)) {
    throw new Error(`Invalid status or issue URL for ${id}`);
  }
  const n = index + 1;
  return { ...item, points, sprint: n <= 4 ? '1' : n <= 7 ? '2' : n <= 9 ? '3' : n === 10 ? '3–4' : '4' };
});
const cell = value => String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;')
  .replace(/>/g, '&gt;').replace(/\|/g, '&#124;').replace(/[\r\n]+/g, ' ').replace(/\[/g, '&#91;').replace(/\]/g, '&#93;');
const rows = stories.map(item => `| [${cell(item.title.trim())}](${item.content.url}) | ${item.sprint} | ${item.points} | ${item.status} |`).join('\n');
const counts = [...knownStatuses].map(status => `| ${status} | ${stories.filter(item => item.status === status).length} |`).join('\n');
const remaining = stories.slice(0, 4).filter(item => item.status !== 'Done').reduce((sum, item) => sum + item.points, 0);
const path = resolve(root, 'docs/KANBAN.md');
const previous = readFileSync(path, 'utf8');
const text = `# ThenFrame — Kanban Snapshot

[Open the live GitHub Kanban](https://github.com/users/phangsx25/projects/1)

This is a one-way snapshot: **GitHub Projects → this document**. Edit cards in Projects; editing Markdown does not move cards. See [automatic sync setup](KANBAN_SYNC.md).

**Last snapshot change:** ${new Date().toISOString()} (UTC). Unchanged runs keep this timestamp.

## Status meaning

- **Backlog:** Not selected for current work.
- **Sprint Backlog:** Selected, not started.
- **In progress:** Development underway.
- **In review:** Ready for review; merge, testing or acceptance may still be pending.
- **Done:** Meets the agreed Definition of Done. The sync copies statuses; it does not certify acceptance.

## Current cards

| Story | Sprint | Points | Status |
| --- | --- | --- | --- |
${rows}

Points and sprint allocation use the [product backlog baseline](PRODUCT_BACKLOG.md), not an empty or conflicting board Estimate field. US10's 8 points apply to the whole story across Sprints 3–4.

## Status totals

| Status | Stories |
| --- | --- |
${counts}

Sprint 1 has **${remaining}/16 points remaining** according to the latest board statuses. The [burndown](sprint1-burndown.md) records observations only during 5–18 November 2026; after that its history is preserved. Later board edits can therefore differ from the historical chart. See [verification evidence](VERIFICATION.md) for actual acceptance limits.

## Refresh

Run \`node scripts/sync-kanban.mjs\` to refresh both this table and the Sprint 1 burndown from one board export. Once configured on the default branch, the workflow runs hourly and can be dispatched manually. It commits changed generated files only. Future sprint charts are not generated by this Sprint 1 workflow.
`;
// A timestamp alone must not generate a commit every hour.
const normalize = value => value.replace(/^\*\*Last snapshot change:\*\*.*$/m, '').replace(/\r\n/g, '\n');
// Validate/update burndown before publishing the matching Kanban table.
const temporary = mkdtempSync(join(tmpdir(), 'thenframe-kanban-'));
try {
  const input = join(temporary, 'board.json');
  writeFileSync(input, JSON.stringify(board));
  execFileSync(process.execPath, [resolve(root, 'scripts/update-burndown.mjs'), '--input', input], { stdio: 'inherit' });
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
if (normalize(previous) !== normalize(text)) writeFileSync(path, text);
console.log('Kanban sync complete; no GitHub cards changed.');
